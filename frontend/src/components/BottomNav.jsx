const TABS = [
  { path: '/home',  label: 'Accueil',        Icon: HomeIcon },
  { path: '/recap', label: 'Comptes-rendus',  Icon: FileTextIcon },
  { path: '/settings', label: 'Réglages',    Icon: SettingsIcon },
]

export default function BottomNav() {
  const navigate = useNavigate()
  const { pathname } = useLocation()

  return (
    <nav className="flex shrink-0 border-t border-[rgba(255,255,255,0.08)] bg-bg">
      {TABS.map(({ path, label, Icon }) => {
        const active = pathname === path
        return (
          <button
            key={path}
            onClick={() => navigate(path)}
            className={`flex-1 flex flex-col items-center gap-1 py-2.5 text-[10px] font-semibold border-none bg-transparent cursor-pointer transition-colors ${active ? 'text-accent' : 'text-muted'}`}
          >
            <Icon />
            {label}
          </button>
        )
      })}
    </nav>
  )
}
